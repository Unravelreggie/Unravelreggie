export function translateText(text, language) {
  return language === "zh" ? zh[text] ?? text : text;
}

export function translateContent(value, language) {
  if (language !== "zh") return value;
  if (typeof value === "string") return translateText(value, language);
  if (Array.isArray(value)) return value.map((item) => translateContent(item, language));
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translateContent(item, language)]));
  }
  return value;
}

